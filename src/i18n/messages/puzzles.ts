/** A puzzle's difficulty tier, by name. */
export function tierName(tier: 1 | 2 | 3, locale?: Locale): string {
  return translate(puzzleMessages, `tier.${tier}`, undefined, locale);
}

/** A puzzle theme by name, or null for a puzzle without one. */
export function themeName(theme: string | undefined, locale?: Locale): string | null {
  if (!theme) return null;
  const key = `theme.${theme}`;
  if (key in puzzleMessages.en) {
    return translate(puzzleMessages, key as keyof (typeof puzzleMessages)['en'], undefined, locale);
  }
  // A theme the catalog has not met yet still reads as words.
  return theme.replace(/-/g, ' ');
}

/** Why a wrong answer fails, in a sentence. */
export function refutationText(kind: Refutation['kind'], locale?: Locale): string {
  return translate(puzzleMessages, `refute.${kind}`, undefined, locale);
}
