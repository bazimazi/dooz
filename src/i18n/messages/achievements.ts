type AchievementKey = keyof (typeof achievementMessages)['en'];

/** An achievement's name or description by id, or the id itself when it is unknown. */
export function achievementText(
  id: string,
  field: 'name' | 'description',
  locale?: Locale,
): string {
  const key = `${id}.${field}`;
  return key in achievementMessages.en
    ? translate(achievementMessages, key as AchievementKey, undefined, locale)
    : id;
}

/** The heading an achievement group is listed under. */
export function achievementGroupName(
  group: 'Journey' | 'Puzzles' | 'Bot' | 'Arcade' | 'Level',
  locale?: Locale,
): string {
  return translate(achievementMessages, `group.${group}`, undefined, locale);
}
