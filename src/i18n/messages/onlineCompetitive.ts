/**
 * A rating, rank or score in the locale's digits but without grouping, so
 * English still reads "1500" rather than "1,500".
 */
export function formatRating(value: number, locale: Locale = currentLocale()): string {
  return new Intl.NumberFormat(locale, { useGrouping: false }).format(value);
}
